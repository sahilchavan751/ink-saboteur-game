/**
 * Picks a non-repeating prompt pair using the list of already-used indices.
 * When all pairs have been played, it automatically resets the used pool so the game keeps rolling smoothly.
 *
 * @param {number[]} usedIndices - Array of prompt indices already used in this room
 * @returns {{ pair: object, index: number, updatedUsed: number[] }}
 */
export const getShuffledPromptPair = (usedIndices = []) => {
  const total = PROMPT_PAIRS.length;
  let available = [];

  for (let i = 0; i < total; i++) {
    if (!usedIndices.includes(i)) {
      available.push(i);
    }
  }

  // If all prompts have been used, start fresh cycle
  let freshCycle = false;
  if (available.length === 0) {
    available = Array.from({ length: total }, (_, i) => i);
    freshCycle = true;
  }

  const selectedIndex = available[Math.floor(Math.random() * available.length)];
  const updatedUsed = freshCycle ? [selectedIndex] : [...usedIndices, selectedIndex];

  return {
    pair: PROMPT_PAIRS[selectedIndex],
    index: selectedIndex,
    updatedUsed
  };
};

/**
 * Fallback random selector
 */
export const getRandomPromptPair = () => {
  const index = Math.floor(Math.random() * PROMPT_PAIRS.length);
  return PROMPT_PAIRS[index];
};
